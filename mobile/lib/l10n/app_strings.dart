  static List<Locale> get supportedLocales =>
      supportedLanguages.keys.map((code) => Locale(code)).toList();

  /// Look a string up for the locale currently in effect.
  ///
  /// Reads from Flutter's own `Localizations`, so it always agrees with
  /// whatever MaterialApp resolved -- no second source of truth to drift.
  static String of(BuildContext context, String key) {
    final code = Localizations.localeOf(context).languageCode;
    return _all[code]?[key] ?? _en[key] ?? key;
  }

