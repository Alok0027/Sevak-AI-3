/// UI translations, looked up by the locale Flutter has already resolved.
///
/// Deliberately plain maps rather than the ARB + `flutter gen-l10n`
/// pipeline. That pipeline is the right long-term answer, but it puts a
/// codegen step between `git pull` and a build that runs -- and a
/// teammate who forgets it gets a compile error rather than an English
/// string. This is a hackathon repo on several machines; the upgrade to
/// ARB is mechanical (the keys below map one-to-one) and can happen once
/// the translations are settled.
///
/// All six languages carry the full key set. Anything missing still falls
/// back to English rather than showing a raw key, so adding a key in one
/// language never breaks the others.
///
/// NOT translated here, on purpose: patient names, village names,
/// transcripts, and anything Agent 3 generates. Those are data, not
/// interface -- a patient called Meera Patil is called Meera Patil in
/// every language, and her transcript is already in the language she
/// spoke. Machine-translating either would corrupt a medical record.
///
/// TRANSLATION REVIEW: these translations are careful but unreviewed.
/// Clinical wording (risk levels, "overdue", medication compliance)
/// should be checked by a native speaker before this is used with real
/// patients -- a mistranslated risk term is a safety problem, not a
/// cosmetic one.
